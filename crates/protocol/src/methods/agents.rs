//! `agents/*` and `sessions/*`: agent providers and daemon-owned agent
//! sessions (service `coqo.agents@1`, PLAN §7.3).
//!
//! A **session** is one conversation with one agent provider (Claude via
//! ACP, a terminal agent, Coqo's native loop, …). Sessions live in the
//! daemon: they keep running with no UI attached, and their transcript is
//! persisted, so a UI that reattaches sees everything.
//!
//! The data model follows the Agent Client Protocol (ACP, ADR 0005), the main
//! way agents run, but is provider-neutral: content blocks, tool calls with
//! diffs and locations, plans, session modes, slash commands, usage and the
//! billing source.
//!
//! # Reattach
//!
//! 1. `sessions/list` (the sidebar) or `sessions/get` (one chat tab: the
//!    folded state plus `head`, the last update's seq).
//! 2. `coqo/subscribe` to `sessions/updates` with `since: 0` for the whole
//!    transcript, or `since: <last seq seen>` to continue. Seqs are per
//!    session, start at 1, and are stable across daemon restarts. On
//!    `RESUME_GAP` take a fresh snapshot.
//! 3. `sessions/changes` streams [`SessionInfo`] changes (state, title,
//!    mode, closed) for every session, resumable the same way from
//!    [`SessionList::seq`].
//!
//! # State machine
//!
//! [`AgentState`]: `idle` (nothing running) → `working` (a turn runs) →
//! `needs_permission` (a permission request waits for the user) → `working`
//! → `done` (the turn ended) / `idle` (cancelled) / `error`. Providers and
//! daemon features may also report `needs_input` (a question waits) and
//! `blocked`; the agent itself reports through the `set_status` MCP tool
//! (`sessions/setStatus`). [`SessionInfo::state_since`] says since when.
//!
//! # Status
//!
//! On top of the state, the agent's own words: [`AgentStatus`], a short
//! status line ("Running the test suite") with optional progress, set
//! with `sessions/setStatus`. It is cleared when a turn starts, and when a
//! turn ends unless the agent marked it `blocked` or `done` (then it is the
//! outcome, kept until the next turn). Status changes stream on
//! `sessions/changes`; they are not transcript updates.
//!
//! # Acceptance criteria
//!
//! What "done" means for the session's task, as the agent states it:
//! [`SessionInfo::criteria`], each an [`AcceptanceCriterion`] with a stable
//! id (`AC1`, …), its text, a [`CriterionStatus`] and evidence (a test name,
//! a `file:line`). Set and updated with `sessions/setCriteria` (the
//! `set_acceptance_criteria` MCP tool, or the user in the session panel).
//! They last as long as the session; walkthroughs and trace scenarios refer
//! to them by id. Changes stream on `sessions/changes`.


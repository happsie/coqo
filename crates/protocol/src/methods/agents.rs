/// Whether a permission rule allows or rejects what it matches.
#[derive(Clone, Copy, Debug, PartialEq, Eq, Hash, Serialize, Deserialize)]
#[cfg_attr(test, derive(schemars::JsonSchema))]
#[serde(rename_all = "snake_case")]
pub enum RuleDecision {
    /// Answer with an allow option (`allow_once`, else `allow_always`).
    Allow,
    /// Answer with a reject option (`reject_once`, else `reject_always`).
    Reject,
}

/// What a permission rule matches.
///
/// - `execute`: `pattern` is a command prefix, word by word (`cargo test`
///   matches `cargo test -p shop` but not `cargo testing`). Only simple
///   commands match: no shell operators, redirections, substitutions,
///   globs or `~`, no `..`, every absolute path inside the workspace, and
///   never programs such as `rm`, `sudo`, `curl` or a shell.
/// - `edit` and `read`: `pattern` is a glob over paths relative to a
///   workspace root (`src/**`, `docs/*.md`); every file the request touches
///   must be inside the workspace's roots and match.
#[derive(Clone, Debug, PartialEq, Eq, Hash, Serialize, Deserialize)]
#[cfg_attr(test, derive(schemars::JsonSchema))]
pub struct PermissionRuleSpec {
    /// The tool kind: `execute`, `edit` or `read`.
    pub tool: ToolKind,
    /// The command prefix or path glob.
    pub pattern: String,
}

/// A per-workspace auto-approve (or auto-reject) rule. Rules answer a
/// permission request before it reaches the UI; a request no rule matches
/// is asked. A reject rule wins over an allow rule.
#[derive(Clone, Debug, PartialEq, Eq, Serialize, Deserialize)]
#[cfg_attr(test, derive(schemars::JsonSchema))]
#[serde(rename_all = "camelCase")]
pub struct PermissionRule {
    /// Id.
    pub id: PermissionRuleId,
    /// The workspace it belongs to.
    pub workspace: String,
    /// The tool kind: `execute`, `edit` or `read`.
    pub tool: ToolKind,
    /// The command prefix or path glob.
    pub pattern: String,
    /// Allow or reject.
    pub decision: RuleDecision,
    /// Created, Unix milliseconds.
    pub created_at: i64,
}

impl PermissionRule {
    /// What it matches.
    pub fn spec(&self) -> PermissionRuleSpec {
        PermissionRuleSpec {
            tool: self.tool,
            pattern: self.pattern.clone(),
        }
    }
}


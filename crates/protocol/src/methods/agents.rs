/// What an agent session is doing.
#[derive(Clone, Copy, Debug, Default, PartialEq, Eq, Hash, Serialize, Deserialize)]
#[cfg_attr(test, derive(schemars::JsonSchema))]
#[serde(rename_all = "snake_case")]
pub enum AgentState {
    /// Nothing running; ready for a prompt.
    #[default]
    Idle,
    /// A turn is running.
    Working,
    /// The agent waits for the user's answer to a question.
    NeedsInput,
    /// A permission request waits for the user.
    NeedsPermission,
    /// The agent reports it cannot continue without help.
    Blocked,
    /// The last turn or the provider failed.
    Error,
    /// The last turn ended normally.
    Done,
}

impl AgentState {
    /// Whether the user's attention is needed.
    pub fn needs_attention(self) -> bool {
        matches!(
            self,
            Self::NeedsInput | Self::NeedsPermission | Self::Blocked | Self::Error
        )
    }
}


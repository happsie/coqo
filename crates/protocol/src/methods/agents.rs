/// A piece of message content (ACP `ContentBlock`).
#[derive(Clone, Debug, PartialEq, Serialize, Deserialize)]
#[cfg_attr(test, derive(schemars::JsonSchema))]
#[serde(
    tag = "type",
    rename_all = "snake_case",
    rename_all_fields = "camelCase"
)]
pub enum ContentBlock {
    /// Text (Markdown in agent messages).
    Text {
        /// The text.
        text: String,
    },
    /// An image, base64-encoded.
    Image {
        /// MIME type, such as `image/png`.
        mime_type: String,
        /// Base64 data.
        data: String,
        /// Where it came from, if anywhere.
        #[serde(default, skip_serializing_if = "Option::is_none")]
        uri: Option<String>,
    },
    /// A link to a resource the agent can read itself (an `@`-mentioned
    /// file, say).
    ResourceLink {
        /// The resource's URI, such as `file:///src/app/main.rs`.
        uri: String,
        /// Display name.
        name: String,
        /// MIME type.
        #[serde(default, skip_serializing_if = "Option::is_none")]
        mime_type: Option<String>,
        /// Size in bytes.
        #[serde(default, skip_serializing_if = "Option::is_none")]
        size: Option<u64>,
    },
    /// A resource with its contents embedded (a selection, say).
    Resource {
        /// The resource's URI.
        uri: String,
        /// MIME type.
        #[serde(default, skip_serializing_if = "Option::is_none")]
        mime_type: Option<String>,
        /// Its text.
        text: String,
    },
}

impl ContentBlock {
    /// A text block.
    pub fn text(text: impl Into<String>) -> Self {
        Self::Text { text: text.into() }
    }
}

